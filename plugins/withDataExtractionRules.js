/**
 * Android backup rules (T-41, D1). BACKUP_POLICY is the single switch; app.json android.allowBackup must
 * agree with it (a test checks this, so a half swap fails).
 *
 * D1 (Eemil 5.11 T-19, reconfirmed 24.11.2026): backup stays ON. Policy 'exclude-secrets' (active):
 * allowBackup=true; the app database and files ARE backed up, but the expo-secure-store shared prefs
 * (SecureStore.xml: refresh token, logout flag, device id) are excluded from cloud backup and
 * device-to-device transfer (Android 12+, dataExtractionRules) and from Android <= 11 backup
 * (fullBackupContent). A restored phone therefore has no session and gets a new device id.
 * Note: the online settings (server URL, username) are SQLite rows and are backed up with the database;
 * they are not secrets. Legacy secrets in SQLite (preview builds: online_refresh_token, online_device_id) are
 * NOT migrated: src/core/database/legacyOnlineSecrets.ts deletes them on every database open (secure_delete,
 * one-time checkpoint + VACUUM), so a restored or upgraded install has no session and signs in again.
 *
 * Policy 'off' (previous behaviour, kept for a one-line swap back): allowBackup=false and every domain
 * excluded from cloud backup and device transfer.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const RULES_NAME = 'data_extraction_rules';
const FULL_BACKUP_NAME = 'backup_rules';
/** expo-secure-store keeps its encrypted values in this shared-prefs file (SecureStoreModule.kt). */
const SECURE_STORE_PREFS = 'SecureStore.xml';
/** D1 switch: 'exclude-secrets' (active) or 'off'. */
const BACKUP_POLICY = 'exclude-secrets';
const POLICIES = ['off', 'exclude-secrets'];
const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external', 'device_root', 'device_file', 'device_database', 'device_sharedpref'];

function checkPolicy(policy) {
  if (!POLICIES.includes(policy)) throw new Error(`withDataExtractionRules: unknown backup policy ${policy}`);
}

function buildRulesXml(policy = BACKUP_POLICY) {
  checkPolicy(policy);
  const excludes =
    policy === 'off'
      ? DOMAINS.map((d) => `    <exclude domain="${d}" path="." />`).join('\n')
      : `    <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}" />`;
  const note = policy === 'off' ? 'No app data leaves the device.' : 'Backup on; secure-store secrets excluded.';
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by plugins/withDataExtractionRules.js (D1 ${policy}). ${note} -->`,
    '<data-extraction-rules>',
    '  <cloud-backup>',
    excludes,
    '  </cloud-backup>',
    '  <device-transfer>',
    excludes,
    '  </device-transfer>',
    '</data-extraction-rules>',
    '',
  ].join('\n');
}

/** Android <= 11 (minSdk 24) reads fullBackupContent instead of dataExtractionRules. Only for 'exclude-secrets'. */
function buildFullBackupXml(policy = BACKUP_POLICY) {
  checkPolicy(policy);
  if (policy === 'off') return null;
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withDataExtractionRules.js (D1 exclude-secrets), Android <= 11. -->',
    '<full-backup-content>',
    `  <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}" />`,
    '</full-backup-content>',
    '',
  ].join('\n');
}

function applyToManifest(manifest, policy = BACKUP_POLICY) {
  checkPolicy(policy);
  manifest.$ = manifest.$ || {};
  manifest.$['xmlns:tools'] = manifest.$['xmlns:tools'] || 'http://schemas.android.com/tools';
  const app = manifest.application && manifest.application[0];
  if (!app) throw new Error('withDataExtractionRules: AndroidManifest has no <application>');
  app.$ = app.$ || {};
  const attrs = ['android:dataExtractionRules'];
  app.$['android:dataExtractionRules'] = `@xml/${RULES_NAME}`;
  if (policy !== 'off') {
    app.$['android:fullBackupContent'] = `@xml/${FULL_BACKUP_NAME}`;
    attrs.push('android:fullBackupContent');
  }
  const replace = new Set(String(app.$['tools:replace'] || '').split(',').map((s) => s.trim()).filter(Boolean));
  attrs.forEach((a) => replace.add(a));
  app.$['tools:replace'] = [...replace].join(',');
  return manifest;
}

const withDataExtractionRules = (config) => {
  config = withAndroidManifest(config, (c) => {
    applyToManifest(c.modResults.manifest);
    return c;
  });
  return withDangerousMod(config, [
    'android',
    async (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${RULES_NAME}.xml`), buildRulesXml());
      const full = buildFullBackupXml();
      if (full) fs.writeFileSync(path.join(dir, `${FULL_BACKUP_NAME}.xml`), full);
      return c;
    },
  ]);
};

module.exports = withDataExtractionRules;
module.exports.buildRulesXml = buildRulesXml;
module.exports.buildFullBackupXml = buildFullBackupXml;
module.exports.applyToManifest = applyToManifest;
module.exports.DOMAINS = DOMAINS;
module.exports.BACKUP_POLICY = BACKUP_POLICY;
module.exports.POLICIES = POLICIES;
module.exports.SECURE_STORE_PREFS = SECURE_STORE_PREFS;
