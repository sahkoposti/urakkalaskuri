export function normalizePostalCode(raw: string): string {
  return raw.replace(/\D/g, '').slice(0, 5);
}

/** Palauttaa postitoimipaikan, jos postinumero on Varsinais-Suomessa. */
export function lookupPostalLocality(code: string): string | undefined {
  const normalized = normalizePostalCode(code);
  if (normalized.length !== 5) return undefined;
  return LOCALITIES[normalized];
}
